const ours = (text) => text == null || text.includes(GEN) || text.includes("generated by ai-memory-sync");

function claudeLocalWith(text, lines) {
  const inner = `${CL_BEGIN}\n${lines.join("\n")}\n${CL_END}`;
  const t = text ?? "";
  const i = t.indexOf(CL_BEGIN);
  const j = t.indexOf(CL_END);
  if (i >= 0 && j > i) return t.slice(0, i) + inner + t.slice(j + CL_END.length);
  return `${t.trimEnd()}${t.trim() ? "\n\n" : ""}${inner}\n`;
}

function claudeLocalWithout(text) {
  if (text == null) return null;
  const i = text.indexOf(CL_BEGIN);
  const j = text.indexOf(CL_END);
  if (i < 0 || j < i) return text;
  const r = (text.slice(0, i).trimEnd() + "\n" + text.slice(j + CL_END.length).replace(/^\n+/, "")).trim();
  return r ? `${r}\n` : "";
}

export function excludePath(root) {
  const p = git(root, ["rev-parse", "--git-path", "info/exclude"]);
  return p ? resolve(root, p) : null;
}

function excludeWith(text, entries) {
  const inner = `${EX_BEGIN}\n${entries.join("\n")}\n${EX_END}`;
  const t = text ?? "";
  const i = t.indexOf(EX_BEGIN);
  const j = t.indexOf(EX_END);
  if (i >= 0 && j > i) return t.slice(0, i) + inner + t.slice(j + EX_END.length);
  return `${t.trimEnd()}${t.trim() ? "\n\n" : ""}${inner}\n`;
}

function excludeWithout(text) {
  if (text == null) return null;
  const i = text.indexOf(EX_BEGIN);
  const j = text.indexOf(EX_END);
  if (i < 0 || j < i) return text;
  return (text.slice(0, i).trimEnd() + "\n" + text.slice(j + EX_END.length).replace(/^\n+/, "")).replace(/^\n+/, "");
}

/**
 * Desired generated files for `mode`. Returns [{ path, content }] (content null = leave alone) and warnings.
 * Never includes tracked AGENTS.md/CLAUDE.md in local mode.
 */
export function plan(root, mode) {
  const out = [];
  const warnings = [];
  const { block, notes } = buildBlock(root);
  const P = (rel) => join(root, rel);
  const agentsText = readText(P("AGENTS.md"));
  const claudeText = readText(P("CLAUDE.md"));

  if (mode === "git") {
    out.push({ path: P("AGENTS.md"), content: agentsWithBlock(agentsText, block) });
    const linked = symlinkTarget(P("CLAUDE.md")) === "AGENTS.md" || symlinkTarget(P("AGENTS.md")) === "CLAUDE.md";
    if (!linked && !/^@AGENTS\.md[ \t]*$/m.test(claudeText ?? "")) {
      out.push({ path: P("CLAUDE.md"), content: `${(claudeText ?? "").trimEnd()}${claudeText?.trim() ? "\n\n" : ""}@AGENTS.md\n` });
    }
    const cur = readText(P(MDC));
    if (ours(cur)) out.push({ path: P(MDC), content: mdcGit });
    else warnings.push(`${MDC} exists and was not generated by ai-memory-sync; left alone.`);
  } else if (mode === "local") {
    const localDoc = `${GEN} (local mode; not tracked by git). Do not edit. -->\n\n${LOCAL_SECTION}\n${block}\n`;
    out.push({ path: P("AGENTS.local.md"), content: localDoc });
    // Claude Code reads CLAUDE.local.md natively; import AGENTS.md too, because a CLAUDE.local.md
    // can make Claude skip AGENTS.md when the project has no CLAUDE.md importing it.
    const lines = [];
    if (agentsText != null && !/^@AGENTS\.md[ \t]*$/m.test(claudeText ?? "")) lines.push("@AGENTS.md");
    lines.push("@AGENTS.local.md");
    out.push({ path: P("CLAUDE.local.md"), content: claudeLocalWith(readText(P("CLAUDE.local.md")), lines) });
    // Codex: AGENTS.override.md replaces AGENTS.md in the same directory, so it carries AGENTS.md too.
    const ov = readText(P("AGENTS.override.md"));
    if (ours(ov)) {
      const base = agentsText ? removeBlock(agentsText).trimEnd() + "\n\n" : "";
      out.push({
        path: P("AGENTS.override.md"),
        content: `${GEN} (local mode): AGENTS.md + local project memory, for Codex. Edit AGENTS.md instead. -->\n\n${base}${LOCAL_SECTION}\n${block}\n`,
      });
    } else warnings.push("AGENTS.override.md exists and is not ours: Codex will not see the local memory block.");
    const cur = readText(P(MDC));
    if (ours(cur)) out.push({ path: P(MDC), content: mdcLocal(block) });
    else warnings.push(`${MDC} exists and was not generated by ai-memory-sync; left alone.`);
    const ex = excludePath(root);
    if (ex) {
      const entries = [`/${CTX}/`, `/${MDC}`, ...LOCAL_FILES.map((f) => `/${f}`), `/${CONFIG_FILE}`];
      out.push({ path: ex, content: excludeWith(readText(ex), entries) });
    }
  }
  return { files: out, warnings, notes, block };
}

// ---------- scaffold / sync ----------

export function scaffold(root) {
  const changed = [];
  for (const t of TOOLS) mkdirSync(join(root, MEM, t), { recursive: true });
  const w = (rel, text) => {
    const p = join(root, rel);
    if (!existsSync(p) && writeIfChanged(p, text)) changed.push(rel);
  };
  w(`${CTX}/README.md`, README[CTX]);
  w(`${MEM}/README.md`, README[MEM]);
  for (const t of TOOLS) w(`${MEM}/${t}/README.md`, README[t]);
  return changed;
}

export function applyPlan(root, mode) {
  const p = plan(root, mode);
  const changed = [];
  for (const f of p.files) if (f.content != null && writeIfChanged(f.path, f.content)) changed.push(relative(root, f.path) || f.path);
  return { changed, warnings: p.warnings, notes: p.notes };
}

/** Scaffold the folders and generated files. Idempotent. */
export function init(root, { mode } = {}) {
  root = resolve(root);
  const resolved = mode ? { mode, source: "argument" } : resolveMode(root);
  if (resolved.mode === "off") return { root, mode: "off", changed: [], warnings: [] };
  if (resolved.source === "default" || mode) setGitConfigMode(root, resolved.mode);
  const changed = scaffold(root);
  const r = applyPlan(root, resolved.mode);
  return { root, mode: resolved.mode, changed: [...changed, ...r.changed], warnings: r.warnings };
}

/** Copy *.md from `from` into `to`, scrubbed; writes only when content changed. */
function copyNotes(from, to, literals, counts, filter = () => true) {
  const changed = [];
  if (!isDir(from)) return changed;
  for (const f of mdFiles(from)) {
    const raw = readText(join(from, f));
    if (raw == null || !filter(raw)) continue;
    const s = scrub(raw, literals);
    mergeCounts(counts, s.counts);
    if (writeIfChanged(join(to, f), s.text)) changed.push(join(to, f));
  }
  return changed;
}

/** Memory source dirs for a project: Claude default + config extras; Codex/Cursor extras. */
export function sources(root) {
  const cfg = readConfig(root);
  return {
    claude: [...new Set([claudeMemoryDir(root), ...cfg.claudeMemoryDirs])],
    codex: cfg.codexMemoryDirs,
    cursor: cfg.cursorMemoryDirs,
    copy: cfg.copy,
  };
}

export function sync(root) {
  root = resolve(root);
  const { mode } = resolveMode(root);
  if (mode === "off") return { root, mode, changed: [], counts: {}, warnings: [] };
  const changed = scaffold(root);
  const literals = envLiterals(root, readConfig(root).envAllowKeys);
  const counts = {};
  const src = sources(root);
  const memDir = (t) => join(root, MEM, t);
  for (const d of src.claude) changed.push(...copyNotes(d, memDir("claude"), literals, counts));
  for (const d of src.codex) changed.push(...copyNotes(d, memDir("codex"), literals, counts));
  // Codex's global memories folder: only manual notes that mention this project's path.
  const codexNotes = join(CODEX_DIR, "memories", "extensions", "ad_hoc", "notes");
  changed.push(...copyNotes(codexNotes, memDir("codex"), literals, counts, (raw) => raw.includes(root)));
  for (const d of src.cursor) changed.push(...copyNotes(d, memDir("cursor"), literals, counts));
  for (const c of src.copy) changed.push(...copyNotes(c.from, c.to, literals, counts));
  // Scrub notes written directly in the repo too (tools write there).
  for (const t of TOOLS) {
    for (const f of mdFiles(memDir(t))) {
      const p = join(memDir(t), f);
      const s = scrub(readText(p) ?? "", literals);
      mergeCounts(counts, s.counts);
      if (writeIfChanged(p, s.text)) changed.push(p);
    }
  }
  const r = applyPlan(root, mode);
  register(root, src.claude);
  return {
    root,
    mode,
    changed: [...new Set([...changed.map((p) => relative(root, p) || p), ...r.changed])],
    counts,
    notes: r.notes,
    warnings: r.warnings,
  };
}

// ---------- registry: memory dir → repos (for sessions started outside the repo) ----------

const REGISTRY = () => join(STATE_DIR, "registry.json");

export function register(root, memDirs) {
  try {
    const reg = readJson(REGISTRY(), {}) || {};
    let dirty = false;
    for (const d of memDirs) {
      const list = new Set(reg[d] ?? []);
      if (!list.has(root)) {
        list.add(root);
        reg[d] = [...list].sort();
        dirty = true;
      }
    }
    if (dirty) writeIfChanged(REGISTRY(), `${JSON.stringify(reg, null, 2)}\n`);
  } catch {}
}

export function reposForMemoryDir(dir) {
  const reg = readJson(REGISTRY(), {}) || {};
  return (reg[dir] ?? []).filter((r) => existsSync(r));
}

// ---------- mode switching ----------

function deleteIfOurs(p, log) {
  const t = readText(p);
  if (t != null && ours(t)) {
    unlinkSync(p);
    log(`removed ${p}`);
  }
}

/** Remove local-mode artifacts (used when switching to git mode). */
export function removeLocalArtifacts(root, log) {
  deleteIfOurs(join(root, "AGENTS.local.md"), log);
  deleteIfOurs(join(root, "AGENTS.override.md"), log);
  const cl = join(root, "CLAUDE.local.md");
  const t = readText(cl);
  if (t != null) {
    const n = claudeLocalWithout(t);
    if (n === "") (unlinkSync(cl), log(`removed ${cl}`));
    else if (n !== t) (writeIfChanged(cl, n), log(`updated ${cl}`));
  }
  const ex = excludePath(root);
  const et = ex ? readText(ex) : null;
  if (et != null) {
    const n = excludeWithout(et);
    if (n !== et) (writeIfChanged(ex, n), log(`removed ai-memory-sync entries from ${ex}`));
  }
}

/** Undo git-mode edits (used when switching to local mode). Leaves history alone. */
export function removeGitArtifacts(root, log) {
  const warnings = [];
  const agents = join(root, "AGENTS.md");
  const at = readText(agents);
  if (at != null) {
    let n = removeBlock(at);
    if (n.includes(GIT_SECTION.trim())) n = n.replace(GIT_SECTION.trim(), "").replace(/\n{3,}/g, "\n\n").trim();
    n = n.trim() ? `${n.trim()}\n` : "";
    if (n === "" && !isTracked(root, "AGENTS.md")) (unlinkSync(agents), log("removed AGENTS.md (it only held generated content)"));
    else if (n !== at) (writeIfChanged(agents, n), log("removed the generated block from AGENTS.md"));
  }
  const claude = join(root, "CLAUDE.md");
  const ct = readText(claude);
  if (ct != null && ct.trim() === "@AGENTS.md" && !isTracked(root, "CLAUDE.md")) (unlinkSync(claude), log("removed CLAUDE.md (only @AGENTS.md)"));
  else if (ct != null && /^@AGENTS\.md[ \t]*$/m.test(ct)) log("kept the @AGENTS.md import in CLAUDE.md (harmless; remove by hand if you want)");
  for (const rel of [CTX, MDC]) {
    if (isTracked(root, rel)) {
      git(root, ["rm", "-r", "-q", "--cached", "--", rel]);
      log(`untracked ${rel} (staged removal; files stay on disk)`);
      warnings.push(`${rel} was committed before: past commits still contain it. Rewrite history if that matters.`);
    }
  }
  return warnings;
}

/** Switch mode. Caller handles confirmation and public-remote checks for git mode. */
export function switchMode(root, to, log = console.log) {
  root = resolve(root);
  const from = resolveMode(root).mode;
  let warnings = [];
  setGitConfigMode(root, to);
  if (to === "git") {
    const cfgPath = join(root, CONFIG_FILE);
    const raw = readJson(cfgPath, {}) || {};
    if (raw.mode !== "git") {
      writeIfChanged(cfgPath, `${JSON.stringify({ ...raw, mode: "git" }, null, 2)}\n`);
      log(`wrote mode "git" to ${CONFIG_FILE} (commit it so teammates get git mode)`);
    }
    removeLocalArtifacts(root, log);
    const r = init(root, { mode: "git" });
    sync(root);
    warnings = r.warnings;
  } else if (to === "local") {
    if (from === "git") warnings = removeGitArtifacts(root, log);
    const cfgPath = join(root, CONFIG_FILE);
    const raw = readJson(cfgPath, null);
    if (raw && raw.mode === "git" && !isTracked(root, CONFIG_FILE)) writeIfChanged(cfgPath, `${JSON.stringify({ ...raw, mode: "local" }, null, 2)}\n`);
    const r = init(root, { mode: "local" });
    sync(root);
    warnings.push(...r.warnings);
  } else {
    log("mode off: ai-memory-sync will not touch this project. Existing files were left as they are.");
  }
  return { from, to, warnings };
}

