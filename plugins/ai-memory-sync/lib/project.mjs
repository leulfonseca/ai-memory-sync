// ---------- config and mode ----------

export function readConfig(root) {
  const c = readJson(join(root, CONFIG_FILE), {}) || {};
  const list = (k) => (Array.isArray(c[k]) ? c[k] : []).map((p) => resolve(root, expandHome(String(p))));
  return {
    raw: c,
    mode: MODES.includes(c.mode) ? c.mode : null,
    claudeMemoryDirs: list("claudeMemoryDirs"),
    codexMemoryDirs: list("codexMemoryDirs"),
    cursorMemoryDirs: list("cursorMemoryDirs"),
    envAllowKeys: Array.isArray(c.envAllowKeys) ? c.envAllowKeys.map(String) : [],
    copy: (Array.isArray(c.copy) ? c.copy : [])
      .filter((x) => x && x.from && x.to)
      .map((x) => ({ from: resolve(root, expandHome(x.from)), to: resolve(root, x.to) })),
  };
}

const isGitRepo = (root) => existsSync(join(root, ".git"));
export const isTracked = (root, path) => Boolean(git(root, ["ls-files", "--", path]));

/** Resolve the effective mode: env > git config (per clone) > .ai-memory-sync.json > auto-detect. */
export function resolveMode(root) {
  if (process.env.AI_MEMORY_SYNC === "0") return { mode: "off", source: "env AI_MEMORY_SYNC=0" };
  const gc = isGitRepo(root) ? git(root, ["config", "--local", "--get", "ai-memory-sync.mode"]) : null;
  if (MODES.includes(gc)) return { mode: gc, source: "git config ai-memory-sync.mode" };
  const cfg = readConfig(root);
  if (cfg.mode) return { mode: cfg.mode, source: CONFIG_FILE };
  if (isGitRepo(root) && isTracked(root, CTX)) return { mode: "git", source: "auto (docs/ai-context is tracked)" };
  return { mode: "local", source: "default" };
}

export function setGitConfigMode(root, mode) {
  if (isGitRepo(root)) git(root, ["config", "--local", "ai-memory-sync.mode", mode]);
}

