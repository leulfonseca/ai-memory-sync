/** Body of a memory note without YAML frontmatter, plus name/description. */
export function parseNote(raw, file) {
  const text = raw.replace(/\r\n/g, "\n");
  const fm = text.match(/^---\n([\s\S]*?)\n---[ \t]*\n?/);
  const meta = {};
  for (const line of (fm?.[1] ?? "").split("\n")) {
    const m = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (m) meta[m[1]] = m[2].replace(/^(["'])(.*)\1$/, "$2");
  }
  return {
    name: meta.name || basename(file).replace(/\.md$/, ""),
    description: meta.description || "",
    body: text.slice(fm ? fm[0].length : 0).trim(),
  };
}

const SECTIONS = [
  ["shared", "Shared"],
  ["claude", "From Claude Code"],
  ["codex", "From Codex"],
  ["cursor", "From Cursor"],
];
const SKIP_NOTES = new Set(["README.md", "MEMORY.md"]);

const mdFiles = (dir) => {
  try {
    return readdirSync(dir)
      .filter((f) => f.endsWith(".md") && !f.startsWith("."))
      .sort();
  } catch {
    return [];
  }
};

const neutralizeMarkers = (s) =>
  s.replaceAll(BEGIN_PREFIX, "&lt;!-- BEGIN:ai-memory").replaceAll(END, "&lt;!-- END:ai-memory -->");

/** Build the generated block (markers included) from docs/ai-context/memory. */
export function buildBlock(root) {
  let out = "";
  let n = 0;
  for (const [dir, title] of SECTIONS) {
    const d = join(root, MEM, dir);
    const files = mdFiles(d).filter((f) => !SKIP_NOTES.has(f));
    if (!files.length) continue;
    out += `\n### ${title}\n`;
    for (const f of files) {
      const note = parseNote(readText(join(d, f)) ?? "", f);
      const body = neutralizeMarkers(note.body.replace(/^#{1,4} /gm, "##### "));
      out += `\n#### ${note.name}${note.description ? ` (${note.description})` : ""}\n\n${body}\n`;
      n++;
    }
  }
  if (!n) out = "\n_No notes yet._\n";
  const block = `${BEGIN}\n\n## Project memory\n\nLong-term notes from every AI tool working on this repo. Source files: \`docs/ai-context/memory/\`.\n${out}\n${END}`;
  return { block: scrub(block, envLiterals(root, readConfig(root).envAllowKeys)).text, notes: n };
}

/** Replace (or append) the generated block inside `text`. Everything outside the markers is preserved. */
export function upsertBlock(text, block) {
  const i = text.indexOf(BEGIN_PREFIX);
  const j = i >= 0 ? text.indexOf(END, i) : -1;
  if (i >= 0 && j > i) return text.slice(0, i) + block + text.slice(j + END.length);
  return `${text.trimEnd()}${text.trim() ? "\n\n" : ""}${block}\n`;
}

/** Remove the generated block (and the blank lines before it). */
export function removeBlock(text) {
  const i = text.indexOf(BEGIN_PREFIX);
  const j = i >= 0 ? text.indexOf(END, i) : -1;
  if (i < 0 || j < i) return text;
  const before = text.slice(0, i).replace(/\n+$/, "\n");
  const after = text.slice(j + END.length).replace(/^\n+/, "");
  const res = (before.trim() ? before : "") + (after ? (before.trim() ? "\n" : "") + after : "");
  return res.trim() ? res.replace(/\n*$/, "\n") : "";
}

/** AGENTS.md content for git mode: add the section once (if missing) and the block. */
export function agentsWithBlock(text, block) {
  let t = text ?? "";
  if (!t.includes(SECTION_HEADING)) {
    const i = t.indexOf(BEGIN_PREFIX);
    if (i >= 0) t = `${t.slice(0, i)}${GIT_SECTION}\n${t.slice(i)}`;
    else t = `${t.trimEnd()}${t.trim() ? "\n\n" : ""}${GIT_SECTION}`;
  }
  return upsertBlock(t, block);
}

const symlinkTarget = (p) => {
  try {
    return lstatSync(p).isSymbolicLink() ? basename(readlinkSync(p)) : null;
  } catch {
    return null;
  }
};

